"""Pydantic schemas for baseline analysis requests and responses."""

from __future__ import annotations

from datetime import datetime
from typing import Any
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field, model_validator

from app.scoring.models import (
    CategoryScoreDetail,
    EvidenceTraceItem,
    RequirementTraceItem,
    RiskIndicator,
    ScorePenaltyDetail,
    ScoreReason,
    ScoringWeights,
)


class BaselineAnalysisRequest(BaseModel):
    """Payload to trigger the complete baseline analysis workflow."""
    resume_id: UUID | None = None
    resume_version_id: UUID | None = None
    job_description_id: UUID | None = None
    custom_weights: ScoringWeights | None = None

    model_config = ConfigDict(extra="forbid")


class RecommendationDetail(BaseModel):
    """Structured recommendation item linked to requirements and evidence."""
    id: UUID
    agent_name: str
    category: str
    title: str
    description: str
    priority: str = "medium"
    requirement_id: UUID | None = None
    evidence_ids: list[UUID] = Field(default_factory=list)
    suggested_action: str


class BaselineReportResponse(BaseModel):
    """Comprehensive, fully explainable baseline analysis report."""
    analysis_id: UUID
    owner_id: UUID
    resume_version_id: UUID
    job_description_id: UUID
    has_target_job: bool = True
    created_at: datetime
    status: str = "completed"
    score_name: str = "XAI-ResOpt ATS Compatibility Score"
    calculation_version: str = "xai-resopt-v1.0-deterministic"
    category_pillars: dict[str, Any] = Field(default_factory=dict)
    
    # Core score metrics
    overall_score: float = Field(ge=0.0, le=100.0)
    overall_score_normalized: float = Field(ge=0.0, le=1.0)
    raw_weighted_score: float = Field(ge=0.0, le=1.0)
    total_penalty: float = Field(ge=0.0, le=1.0)
    category_scores: dict[str, CategoryScoreDetail] = Field(default_factory=dict)
    
    # Qualitative insights
    strengths: list[str] = Field(default_factory=list)
    weaknesses: list[str] = Field(default_factory=list)
    mandatory_skill_gaps: list[str] = Field(default_factory=list)
    preferred_skill_gaps: list[str] = Field(default_factory=list)
    ats_risks: list[RiskIndicator] = Field(default_factory=list)
    unsupported_claims: list[str] = Field(default_factory=list)
    evidence_confidence: float = Field(ge=0.0, le=1.0)
    
    # Recommendations & traceability
    recommendations: list[RecommendationDetail] = Field(default_factory=list)
    evidence_references: list[EvidenceTraceItem] = Field(default_factory=list)
    requirement_coverage: list[RequirementTraceItem] = Field(default_factory=list)
    penalties: list[ScorePenaltyDetail] = Field(default_factory=list)
    reasons: list[ScoreReason] = Field(default_factory=list)
    traceability_map: dict[str, list[str]] = Field(default_factory=dict)


class ScoreBreakdownResponse(BaseModel):
    """Detailed score calculation breakdown for an analysis."""
    analysis_id: UUID
    score_name: str = "XAI-ResOpt ATS Compatibility Score"
    calculation_version: str = "xai-resopt-v1.0-deterministic"
    overall_score: float
    overall_score_normalized: float
    raw_weighted_score: float
    total_penalty: float
    category_scores: dict[str, CategoryScoreDetail]
    penalties: list[ScorePenaltyDetail]
    reasons: list[ScoreReason]


class AgentRunRecord(BaseModel):
    """Execution telemetry record for an agent."""
    id: UUID
    analysis_id: UUID
    request_id: str | None = None
    agent_name: str
    status: str
    start_time: datetime | None = None
    end_time: datetime | None = None
    duration_ms: int | None = None
    retry_count: int = 0
    retrieval_count: int = 0
    model_calls: int = 0
    token_usage: dict[str, Any] | None = None
    error: str | None = None
    recovery_status: str | None = None
    final_score: float | None = None
    created_at: datetime
    output: dict[str, Any] | None = None


class AgentRunsResponse(BaseModel):
    """List of agent runs associated with an analysis."""
    analysis_id: UUID
    total_runs: int
    agent_runs: list[AgentRunRecord]


class RecommendationsResponse(BaseModel):
    """Recommendations generated by analysis agents."""
    analysis_id: UUID
    total_recommendations: int
    recommendations: list[RecommendationDetail]


class RequirementsCoverageResponse(BaseModel):
    """Requirement fulfillment and gap tracking."""
    analysis_id: UUID
    total_requirements: int
    matched_count: int
    missing_count: int
    requirements: list[RequirementTraceItem]


class EvidenceTraceResponse(BaseModel):
    """Grounded evidence items and provenance mapping."""
    analysis_id: UUID
    total_evidence_items: int
    evidence_confidence_score: float
    unsupported_claims: list[str]
    evidence_items: list[EvidenceTraceItem]


class AnalysisSummaryItem(BaseModel):
    """Concise summary item for user's dashboard listing."""
    id: UUID
    status: str
    overall_score: float | None = None
    created_at: datetime
    resume_id: UUID | None = None
    resume_version_id: UUID | None = None
    resume_title: str | None = None
    job_description_id: UUID | None = None
    job_title: str | None = None


class CopilotCitation(BaseModel):
    """Provenance citation linking copilot assertions to verifiable evidence."""
    id: str | None = None
    text: str = ""
    source: str = ""
    confidence: float = 0.95
    support_status: str = "known"  # known, inferred, unknown, unsupported

    @model_validator(mode="before")
    @classmethod
    def handle_legacy_fields(cls, data: Any) -> Any:
        if isinstance(data, dict):
            if "quote" in data and not data.get("text"):
                data["text"] = data["quote"]
            if "relevance" in data and "confidence" not in data:
                data["confidence"] = data["relevance"]
        return data


class CopilotChatRequest(BaseModel):
    """Query sent to the context-aware analysis copilot."""
    message: str


class CopilotChatResponse(BaseModel):
    """Context-grounded assistant reply with provenance labels and citations."""
    response: str = ""
    citations: list[CopilotCitation] = Field(default_factory=list)
    support_label: str = "Known from evidence"  # Known from evidence, Inferred, Unknown, Unsupported
    suggested_actions: list[str] = Field(default_factory=list)
    analysis_id: UUID | None = None
    user_query: str | None = None

    @model_validator(mode="before")
    @classmethod
    def handle_legacy_fields(cls, data: Any) -> Any:
        if isinstance(data, dict):
            if "answer" in data and not data.get("response"):
                data["response"] = data["answer"]
        return data


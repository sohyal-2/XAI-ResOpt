"""Pydantic schemas and data models for Optimizer, Critic, and Fact-Check agents."""

from __future__ import annotations

from uuid import UUID, uuid4

from pydantic import BaseModel, ConfigDict, Field


class ProposedChange(BaseModel):
    """An individual proposed resume modification linked strictly to source evidence."""
    change_id: UUID = Field(default_factory=uuid4)
    section: str = Field(description="Target section: experience, summary, skills, projects, education")
    change_type: str = Field(
        default="bullet",
        description="Type of change: bullet, summary, skills, ordering, clarity, impact",
    )
    before_text: str = Field(description="Original resume text prior to proposed rewrite")
    after_text: str = Field(description="Optimized, ATS-friendly proposed text")
    reason: str = Field(description="Concrete reason why this change improves ATS compatibility or clarity")
    evidence_ids: list[UUID] = Field(
        default_factory=list,
        description="IDs of candidate evidence items backing the claims in after_text",
    )
    risk_level: str = Field(default="low", description="low, medium, or high risk")
    support_status: str = Field(
        default="SUPPORTED",
        description="SUPPORTED, PARTIALLY_SUPPORTED, or UNSUPPORTED",
    )
    target_requirement_ids: list[UUID] = Field(
        default_factory=list,
        description="Job requirement IDs addressed by this change",
    )
    model_config = ConfigDict(extra="ignore")


class OptimizerAgentOutput(BaseModel):
    """Output generated by the Optimizer Agent."""
    status: str = "completed"
    proposed_changes: list[ProposedChange] = Field(default_factory=list)
    summary_optimization: ProposedChange | None = None
    skill_section_optimization: ProposedChange | None = None
    ordering_improvements: list[str] = Field(default_factory=list)
    total_changes_proposed: int = 0
    grounded_evidence_count: int = 0


class CriticEvaluation(BaseModel):
    """Multi-dimensional evaluation for an individual proposed change."""
    change_id: UUID
    relevance_score: float = Field(ge=0.0, le=1.0, description="Relevance to target job requirements")
    clarity_score: float = Field(ge=0.0, le=1.0, description="Clarity and directness of phrasing")
    grammar_score: float = Field(ge=0.0, le=1.0, description="Grammatical correctness and tense consistency")
    conciseness_score: float = Field(ge=0.0, le=1.0, description="Conciseness and elimination of fluff")
    keyword_quality_score: float = Field(ge=0.0, le=1.0, description="Natural keyword density and phrasing")
    ats_compatibility_score: float = Field(ge=0.0, le=1.0, description="ATS safe layout and character use")
    professional_quality_score: float = Field(ge=0.0, le=1.0, description="Active verb strength and professional tone")
    factual_risk_score: float = Field(ge=0.0, le=1.0, description="Risk of exaggerating or misrepresenting claims")
    overall_critic_score: float = Field(ge=0.0, le=1.0, description="Weighted aggregate critic score")
    verdict: str = Field(description="APPROVED, NEEDS_REVISION, or REJECTED")
    feedback: list[str] = Field(default_factory=list)


class CriticAgentOutput(BaseModel):
    """Output generated by the Critic Agent."""
    status: str = "completed"
    evaluations: list[CriticEvaluation] = Field(default_factory=list)
    approved_changes: list[ProposedChange] = Field(default_factory=list)
    rejected_changes: list[ProposedChange] = Field(default_factory=list)
    average_critic_score: float = Field(ge=0.0, le=1.0, default=0.0)


class FactCheckVerification(BaseModel):
    """Fact-checking verification for an individual proposed change."""
    change_id: UUID
    metrics_verified: bool = Field(default=True, description="All numerical/percentage metrics verified against evidence")
    companies_verified: bool = Field(default=True, description="All employer/company names verified against evidence")
    dates_verified: bool = Field(default=True, description="All date ranges and timelines verified")
    titles_verified: bool = Field(default=True, description="All job titles and roles verified")
    technologies_verified: bool = Field(default=True, description="All mentioned frameworks, skills, and tools verified")
    responsibilities_verified: bool = Field(default=True, description="Responsibilities align with candidate experience")
    certifications_verified: bool = Field(default=True, description="Certifications verified")
    projects_verified: bool = Field(default=True, description="Projects verified against candidate portfolio/resume")
    numerical_claims_verified: bool = Field(default=True, description="No unbacked revenue, scale, or user counts")
    is_grounded: bool = Field(default=True, description="True if change introduces zero ungrounded assertions")
    verdict: str = Field(description="PASSED or FAILED")
    hallucination_flags: list[str] = Field(default_factory=list)
    evidence_provenance: list[UUID] = Field(default_factory=list)
    rejection_reason: str | None = None


class FactCheckAgentOutput(BaseModel):
    """Output generated by the Fact-Check Agent."""
    status: str = "completed"
    verifications: list[FactCheckVerification] = Field(default_factory=list)
    passed_changes: list[ProposedChange] = Field(default_factory=list)
    rejected_changes: list[ProposedChange] = Field(default_factory=list)
    hallucination_count: int = 0
    pass_rate: float = Field(ge=0.0, le=100.0, default=100.0)
